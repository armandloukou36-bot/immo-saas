export function Sidebar({ orgName }: { orgName: string }) {
  const pathname = usePathname();
  const [open, setOpen] = useState(false);

  return (
    <>
      {/* Bouton d'ouverture mobile */}
      <button
        type="button"
        onClick={() => setOpen(true)}
        aria-label="Ouvrir le menu"
        className="lg:hidden fixed top-3 left-3 z-40 p-2 rounded-lg bg-navy-900 text-white shadow-lg"
      >
        <svg className="w-5 h-5" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={2}>
          <path strokeLinecap="round" strokeLinejoin="round" d="M3.75 6.75h16.5M3.75 12h16.5m-16.5 5.25h16.5" />
        </svg>
      </button>

      {/* Arrière-plan mobile */}
      {open && (
        <div className="lg:hidden fixed inset-0 z-40 bg-navy-950/60" onClick={() => setOpen(false)} role="presentation" />
      )}

      <aside className={`sidebar ${open ? 'open' : ''}`}>
        <div className="sidebar-header">
          <div className="sidebar-logo">
            Immo<span className="text-white">SaaS</span>
          </div>
          <p className="text-[10px] text-navy-500 mt-0.5 text-center truncate" title={orgName}>
            {orgName}
          </p>
        </div>

        <nav className="sidebar-nav">
          {navItems.map((section) => (
            <div key={section.section} className="sidebar-section">
              <div className="sidebar-section-title">{section.section}</div>
              {section.items.map((item) => {
                const isActive = pathname === item.href || pathname.startsWith(item.href + '/');
                return (
                  <Link
                    key={item.href}
                    href={item.href}
                    onClick={() => setOpen(false)}
                    className={`sidebar-link ${isActive ? 'active' : ''}`}
                  >
                    <Icon href={item.href} />
                    <span>{item.label}</span>
                  </Link>
                );
              })}
            </div>
          ))}
        </nav>

        <div className="sidebar-footer">
          <div className="text-xs text-navy-500 text-center">v1.0.0 · Immo SaaS</div>
        </div>
      </aside>
    </>
  );
}
